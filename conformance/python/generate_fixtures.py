# Values from libm functions (atan, pow) can differ in the last bit between
# platforms, so --check compares floats with this relative tolerance.
CHECK_RTOL = 1e-12
_check_failures: list[str] | None = None


def _write(name: str, value: Any) -> None:
    text = json.dumps(value, indent=4, sort_keys=True) + "\n"
    if _check_failures is not None:
        path = FIXTURE_DIR / name
        committed = json.loads(path.read_text()) if path.exists() else None
        _check_failures.extend(f"{name}{where}" for where in _differences(committed, json.loads(text)))
        return
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    (FIXTURE_DIR / name).write_text(text)


def _differences(committed: Any, generated: Any, where: str = "") -> list[str]:
    if isinstance(committed, float) and isinstance(generated, float):
        if committed == generated or abs(committed - generated) <= CHECK_RTOL * max(abs(committed), abs(generated)):
            return []
    elif isinstance(committed, dict) and isinstance(generated, dict):
        if committed.keys() == generated.keys():
            return [d for key in committed for d in _differences(committed[key], generated[key], f"{where}.{key}")]
    elif isinstance(committed, list) and isinstance(generated, list):
        if len(committed) == len(generated):
            return [
                d
                for i, (a, b) in enumerate(zip(committed, generated, strict=True))
                for d in _differences(a, b, f"{where}[{i}]")
            ]
    elif type(committed) is type(generated) and committed == generated:
        return []
    return [f"{where}: committed {committed!r}, generated {generated!r}"]


def _dart_fixture_library() -> str:
    entries = []
    for path in sorted(FIXTURE_DIR.glob("*.json")):
        entries.append(f"  {path.name!r}: r'''{path.read_text()}''',")
    return "\n".join(
        [
            "// Generated by conformance/python/generate_fixtures.py.",
            "// Do not edit by hand.",
            "",
            "const fixtureJsonByName = <String, String>{",
            *entries,
            "};",
            "",
        ]
    )


def _write_dart_fixture_library() -> None:
    path = DART_TEST_DIR / "fixtures.g.dart"
    if _check_failures is not None:
        if not path.exists() or path.read_text() != _dart_fixture_library():
            _check_failures.append("test/fixtures.g.dart does not embed the committed JSON fixtures")
        return
    DART_TEST_DIR.mkdir(parents=True, exist_ok=True)
    path.write_text(_dart_fixture_library())


def _detections(frame: dict[str, Any]) -> sv.Detections:
    xyxy = np.asarray(frame["xyxy"], dtype=np.float64).reshape((-1, 4))
    confidence = frame.get("confidence")
    class_id = frame.get("class_id")
    return sv.Detections(
        xyxy=xyxy,
        confidence=None if confidence is None else np.asarray(confidence, dtype=np.float64),
        class_id=None if class_id is None else np.asarray(class_id, dtype=int),
        # Carried through tracker output so rows map back to input detections exactly.
        data={INPUT_INDEX_KEY: np.arange(len(xyxy))},
    )


